// Self-executing Level Validator (Simulates and verifies moves for all levels)
(function validateWarehouseBoyLevels() {
    console.group("%c📦 Warehouse Boy Level Validator & Diagnostics Report", "color: #f59e0b; font-weight: bold; font-size: 15px;");

    window.warehouseBoyLevels.forEach(level => {
        const id = level.id;
        const map = level.map;
        const solution = level.solution || "";
        
        let solutionExists = solution.length > 0 ? "Yes" : "No";
        let solutionLength = solution.length;
        let finalSolved = "No";
        let solutionValidated = "No";
        let pushCount = 0;
        
        if (solutionLength > 0) {
            // Setup local state for simulation
            const rows = map.length;
            const cols = Math.max(...map.map(r => r.length));
            const walls = Array(rows).fill(null).map(() => Array(cols).fill(false));
            const goals = Array(rows).fill(null).map(() => Array(cols).fill(false));
            const crates = [];
            let player = { r: 0, c: 0 };
            
            for (let r = 0; r < rows; r++) {
                for (let c = 0; c < map[r].length; c++) {
                    const char = map[r][c];
                    if (char === "#") {
                        walls[r][c] = true;
                    } else if (char === "." || char === "G") {
                        goals[r][c] = true;
                    } else if (char === "$" || char === "C") {
                        crates.push({ r, c });
                    } else if (char === "*") {
                        goals[r][c] = true;
                        crates.push({ r, c });
                    } else if (char === "@" || char === "P") {
                        player = { r, c };
                    } else if (char === "+") {
                        goals[r][c] = true;
                        player = { r, c };
                    }
                }
            }
            
            let isLegit = true;
            for (let idx = 0; idx < solution.length; idx++) {
                const char = solution[idx].toLowerCase();
                let dr = 0, dc = 0;
                if (char === 'u') dr = -1;
                else if (char === 'd') dr = 1;
                else if (char === 'l') dc = -1;
                else if (char === 'r') dc = 1;
                else {
                    isLegit = false;
                    break;
                }
                
                const nr = player.r + dr;
                const nc = player.c + dc;
                
                // Wall boundary or collision check
                if (nr < 0 || nr >= rows || nc < 0 || nc >= cols || walls[nr][nc]) {
                    isLegit = false;
                    break;
                }
                
                // Crate push check
                const crateIdx = crates.findIndex(c => c.r === nr && c.c === nc);
                if (crateIdx !== -1) {
                    const cbr = nr + dr;
                    const cbc = nc + dc;
                    if (cbr < 0 || cbr >= rows || cbc < 0 || cbc >= cols || walls[cbr][cbc]) {
                        isLegit = false;
                        break;
                    }
                    if (crates.some(c => c.r === cbr && c.c === cbc)) {
                        isLegit = false;
                        break;
                    }
                    crates[crateIdx].r = cbr;
                    crates[crateIdx].c = cbc;
                    pushCount++;
                }
                
                player.r = nr;
                player.c = nc;
            }
            
            if (isLegit) {
                const allOnGoals = crates.every(crate => goals[crate.r][crate.c]);
                if (allOnGoals) {
                    finalSolved = "Yes";
                    solutionValidated = "Yes";
                }
            }
        }
        
        // Update level object properties just in case
        level.solutionValidated = (solutionValidated === "Yes");
        if (solutionValidated === "Yes") {
            level.solutionPushes = pushCount;
            level.solutionMoves = solutionLength;
        }
        
        console.log(
            `Level ${id}\n` +
            `Solution Exists: ${solutionExists}\n` +
            `Solution Length: ${solutionLength}\n` +
            `Solution Push Count: ${pushCount}\n` +
            `Solution Validated: ${solutionValidated}\n` +
            `Final State Solved: ${finalSolved}`
        );
    });

    console.groupEnd();
})();
